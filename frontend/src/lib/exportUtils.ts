import { GraphData, CodebaseHealthResponse } from "@/types";

export function generateMermaidDiagram(graphData: GraphData): string {
  const lines = ["flowchart LR"];
  const idMap = new Map<string, string>();

  graphData.nodes.forEach((n, idx) => {
    const safeId = `N${idx}`;
    idMap.set(n.id, safeId);
    const cleanLabel = n.label.replace(/"/g, "'");
    lines.push(`    ${safeId}["${cleanLabel}"]`);
  });

  graphData.edges.forEach((e) => {
    const src = idMap.get(e.source);
    const tgt = idMap.get(e.target);
    if (src && tgt) {
      lines.push(`    ${src} --> ${tgt}`);
    }
  });

  return lines.join("\n");
}

export function generateMarkdownArchitectureReport(
  repoName: string,
  repoId: string,
  graphData: GraphData,
  healthData?: CodebaseHealthResponse | null
): string {
  const mermaid = generateMermaidDiagram(graphData);
  const totalNodes = graphData.nodes.length;
  const totalEdges = graphData.edges.length;

  const smellsSection =
    healthData && healthData.smells.length > 0
      ? `\n## ⚠️ Architectural Smells & Quality Warnings (${healthData.smells.length} Detected)
${healthData.smells
  .map(
    (s) =>
      `- **[${s.severity.toUpperCase()}] ${s.title}**: ${s.description}\n  - *Fix Tip*: ${s.refactoring_tip}\n  - *Affected Files*: ${s.affected_files.join(", ")}`
  )
  .join("\n")}`
      : "\n## 🛡️ Architecture Smells\nNo critical architecture anti-patterns detected. Clean modular structure.";

  return `# 🗺️ Architecture Snapshot: ${repoName}

> Generated by **CodeAtlas** on ${new Date().toISOString().split("T")[0]}  
> Repository ID: \`${repoId}\`

---

## 📊 High-Level Metrics
- **Total Modules (Nodes)**: ${totalNodes}
- **Architectural Dependencies (Edges)**: ${totalEdges}
${
  healthData
    ? `- **Codebase Health Score**: ${healthData.health_score}/100 (${healthData.health_rating})
- **Total Lines Analyzed**: ${healthData.total_lines.toLocaleString()}
- **Graph Density**: ${(healthData.graph_density * 100).toFixed(1)}%`
    : ""
}

---

## 🏛️ Dependency Topology (Mermaid)

\`\`\`mermaid
${mermaid}
\`\`\`

---

## 📦 Module Inventory

| File Path | Internal In-Degree | Internal Out-Degree |
| :--- | :--- | :--- |
${graphData.nodes
  .map((n) => `| \`${n.id}\` | ${n.in_degree} | ${n.out_degree} |`)
  .join("\n")}
${smellsSection}

---

*Generated automatically via CodeAtlas Architecture Exploration Engine.*
`;
}

export function exportGraphAsSVG(repoName: string, graphData: GraphData) {
  const width = 1400;
  const height = 900;
  const nodeWidth = 180;
  const nodeHeight = 56;

  const cols = Math.ceil(Math.sqrt(graphData.nodes.length * 1.5));
  const nodeCoords = new Map<string, { x: number; y: number }>();

  graphData.nodes.forEach((n, idx) => {
    const row = Math.floor(idx / cols);
    const col = idx % cols;
    const x = 80 + col * (nodeWidth + 60);
    const y = 80 + row * (nodeHeight + 60);
    nodeCoords.set(n.id, { x, y });
  });

  const edgeSvgLines: string[] = [];
  graphData.edges.forEach((e) => {
    const src = nodeCoords.get(e.source);
    const tgt = nodeCoords.get(e.target);
    if (src && tgt) {
      const x1 = src.x + nodeWidth;
      const y1 = src.y + nodeHeight / 2;
      const x2 = tgt.x;
      const y2 = tgt.y + nodeHeight / 2;
      const mx = (x1 + x2) / 2;
      edgeSvgLines.push(
        `<path d="M ${x1} ${y1} C ${mx} ${y1}, ${mx} ${y2}, ${x2} ${y2}" fill="none" stroke="#38bdf8" stroke-width="2" marker-end="url(#arrow)" opacity="0.75" />`
      );
    }
  });

  const nodeSvgElements: string[] = [];
  graphData.nodes.forEach((n) => {
    const coords = nodeCoords.get(n.id) || { x: 0, y: 0 };
    const safeLabel = n.label.replace(/&/g, "&amp;").replace(/</g, "&lt;");
    nodeSvgElements.push(`
      <g transform="translate(${coords.x}, ${coords.y})">
        <rect width="${nodeWidth}" height="${nodeHeight}" rx="8" fill="#18181b" stroke="#3f3f46" stroke-width="1.5" />
        <text x="14" y="26" font-family="monospace" font-size="12" font-weight="600" fill="#f4f4f5">${safeLabel}</text>
        <text x="14" y="44" font-family="monospace" font-size="10" fill="#a1a1aa">in:${n.in_degree} · out:${n.out_degree}</text>
      </g>
    `);
  });

  const svgContent = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" style="background-color: #09090b;">
  <defs>
    <marker id="arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M 0 1 L 10 5 L 0 9 z" fill="#38bdf8" />
    </marker>
  </defs>
  <text x="80" y="45" font-family="sans-serif" font-size="18" font-weight="bold" fill="#ffffff">${repoName} · Architecture Dependency Graph</text>
  <g>${edgeSvgLines.join("\n")}</g>
  <g>${nodeSvgElements.join("\n")}</g>
</svg>`;

  const blob = new Blob([svgContent], { type: "image/svg+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${repoName}-architecture-graph.svg`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

